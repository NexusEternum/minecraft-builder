"""
Redstone transport systems from the Minecraft Guide to Creative.

Reference knowledge for prompts — minecart circuits are NOT generated by the model.
Useful for mining scenes, industrial builds, and underground terminals.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class TransportSystem:
  id: str
  name: str
  aliases: tuple[str, ...]
  blocks: tuple[str, ...]
  tip: str


def _b(name: str) -> str:
  if name.startswith("minecraft:"):
    return name
  return f"minecraft:{name}"


