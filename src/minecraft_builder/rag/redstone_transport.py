def detect_transport_system(prompt: str) -> list[TransportSystem]:
  lower = prompt.lower()
  return [s for s in TRANSPORT_SYSTEMS if any(a in lower for a in s.aliases)]


def transport_keywords(system: TransportSystem) -> list[str]:
  return [system.name] + [b.removeprefix("minecraft:").replace("_", " ") for b in system.blocks[:2]]
